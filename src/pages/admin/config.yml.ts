import type { APIRoute } from 'astro';

/**
 * Generates /admin/config.yml for Sveltia CMS at build time.
 * The GitHub repo and branch are detected from the GitHub Actions environment,
 * so nothing needs editing after you fork or rename the repo.
 * For local builds, set CMS_REPO=owner/repo if you want a working config.
 */
export const GET: APIRoute = ({ site }) => {
  const repo = process.env.GITHUB_REPOSITORY || process.env.CMS_REPO || 'OWNER/REPO';
  const branch = process.env.GITHUB_REF_NAME || 'main';
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  const siteUrl = new URL(base + '/', site).href;

  const yaml = `# Generated by src/pages/admin/config.yml.ts. Edit that file, not this one.
backend:
  name: github
  repo: ${repo}
  branch: ${branch}
  commit_messages:
    create: "Add {{collection}}: {{slug}}"
    update: "Update {{collection}}: {{slug}}"
    delete: "Delete {{collection}}: {{slug}}"
    uploadMedia: "Upload {{path}}"
    deleteMedia: "Delete {{path}}"

site_url: ${siteUrl}
display_url: ${siteUrl}
logo_url: ${siteUrl}favicon.svg

media_folder: public/uploads
public_folder: /uploads

collections:
  - name: panels
    label: Panels
    label_singular: Panel
    description: Every electrical panel shown on the website. Click "New Panel" to add one.
    folder: src/content/panels
    extension: md
    format: frontmatter
    create: true
    delete: true
    slug: "{{slug}}"
    identifier_field: title
    summary: "{{title}}"
    sortable_fields: [title, order]
    media_folder: /public/uploads/panels
    public_folder: /uploads/panels
    view_groups:
      - { label: Category, field: category }
    fields:
      - { label: Panel name, name: title, widget: string, hint: "e.g. MCC Panel, 25 kA" }
      - label: Category
        name: category
        widget: relation
        collection: categories
        value_field: "{{slug}}"
        search_fields: [title]
        display_fields: [title]
      - { label: Short summary, name: summary, widget: text, hint: "One or two sentences shown on cards and in search results." }
      - { label: Main image, name: image, widget: image, hint: "Square or 4:3 photo on a light background works best." }
      - label: More images
        name: gallery
        widget: list
        required: false
        field: { label: Image, name: image, widget: image }
      - label: Headline ratings (max 4)
        name: highlights
        widget: list
        required: false
        max: 4
        summary: "{{fields.label}}: {{fields.value}}"
        hint: "Shown on the card and the rating plate, e.g. Voltage / 415 V AC"
        fields:
          - { label: Label, name: label, widget: string }
          - { label: Value, name: value, widget: string }
      - label: Technical specifications
        name: specs
        widget: list
        required: false
        summary: "{{fields.label}}: {{fields.value}}"
        fields:
          - { label: Label, name: label, widget: string }
          - { label: Value, name: value, widget: string }
      - label: Key features
        name: features
        widget: list
        required: false
        field: { label: Feature, name: feature, widget: string }
      - label: Applications
        name: applications
        widget: list
        required: false
        field: { label: Application, name: application, widget: string }
      - { label: Price (optional), name: price, widget: string, required: false, hint: "Shown only when 'Show prices' is on in Site settings." }
      - { label: Featured on home page, name: featured, widget: boolean, default: false }
      - { label: Sort order, name: order, widget: number, value_type: int, default: 99, hint: "Lower numbers appear first." }
      - { label: Draft (hide from site), name: draft, widget: boolean, default: false }
      - { label: Description, name: body, widget: markdown }

  - name: categories
    label: Categories
    label_singular: Category
    description: Product lines used to group panels.
    folder: src/content/categories
    extension: json
    format: json
    create: true
    delete: true
    slug: "{{slug}}"
    identifier_field: title
    fields:
      - { label: Name, name: title, widget: string }
      - { label: Short code, name: code, widget: string, hint: "2–4 letters shown on cards, e.g. CA", pattern: ["^.{1,4}$", "Max 4 characters"] }
      - { label: Description, name: description, widget: text }
      - { label: Sort order, name: order, widget: number, value_type: int, default: 99 }

  - name: settings
    label: Site settings
    editor:
      preview: false
    files:
      - name: site
        label: Company & contact details
        file: src/data/site.json
        format: json
        fields:
          - { label: Company name, name: name, widget: string }
          - { label: Legal name, name: legalName, widget: string }
          - { label: Tagline, name: tagline, widget: string }
          - { label: SEO description, name: description, widget: text }
          - { label: Year established, name: established, widget: number, value_type: int }
          - { label: Director, name: director, widget: string }
          - { label: Phone, name: phone, widget: string, required: false, hint: "e.g. +91 98450 00000" }
          - { label: WhatsApp number, name: whatsapp, widget: string, required: false, hint: "With country code, e.g. 919845000000" }
          - { label: Email, name: email, widget: string, required: false }
          - label: Address
            name: address
            widget: object
            fields:
              - { label: Line 1, name: line1, widget: string }
              - { label: Line 2, name: line2, widget: string }
              - { label: City, name: city, widget: string }
              - { label: State, name: state, widget: string }
              - { label: PIN code, name: pincode, widget: string }
              - { label: Country, name: country, widget: string }
          - { label: GSTIN, name: gst, widget: string }
          - { label: CIN, name: cin, widget: string }
          - { label: IEC, name: iec, widget: string }
          - { label: IndiaMART URL, name: indiamart, widget: string }
          - { label: Form endpoint (optional), name: formEndpoint, widget: string, required: false, hint: "Paste a Formspree URL to receive enquiries by email. Leave empty to use email / WhatsApp links." }
          - { label: Show prices, name: showPrices, widget: boolean, default: false }
`;

  return new Response(yaml, { headers: { 'Content-Type': 'text/yaml; charset=utf-8' } });
};
